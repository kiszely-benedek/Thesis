"""Render the derived vocabulary as the source text of `graph/schema_vocabulary.py`.

Kept apart from the rule (`pydexpi_vocabulary.py`) so the text format can be tested on its own, and
so `scripts/derive_schema_vocabulary.py` stays a few lines.
"""

from __future__ import annotations

import json
from collections.abc import Sequence

from plantgraph.graph.schema_classes import VocabularyRow

_HEADER = '''\
"""The schema's class vocabulary: one row per allowlisted pyDEXPI class (ADR-0058).

GENERATED by `scripts/derive_schema_vocabulary.py` from pyDEXPI {version}; do not edit by hand.
Change `ALLOWLIST` or the rule in `adapters/pydexpi_vocabulary.py`, then run
`uv run python scripts/derive_schema_vocabulary.py`. `tests/test_schema_vocabulary.py` fails if this
file no longer matches the rule. It is a literal table so that `graph/` never imports pyDEXPI.

Columns: class name, Neo4j label chain, category, piping kind, tag prefix, leaf (pyDEXPI class
without subclasses).
"""

from __future__ import annotations

from plantgraph.graph.schema_classes import NodeCategory, PipingKind, VocabularyRow


def _row(
    name: str,
    labels: tuple[str, ...],
    category: str,
    piping_kind: PipingKind | None,
    tag_prefix: str | None,
    leaf: bool,
) -> VocabularyRow:
    return VocabularyRow(
        name=name,
        labels=labels,
        category=NodeCategory(category),
        piping_kind=piping_kind,
        tag_prefix=tag_prefix,
        leaf=leaf,
    )


VOCABULARY: tuple[VocabularyRow, ...] = (
'''


def render_vocabulary_module(rows: Sequence[VocabularyRow], pydexpi_version: str) -> str:
    """The full source text of the generated table module."""
    lines = [_render_row(row) for row in rows]
    return _HEADER.format(version=pydexpi_version) + "\n".join(lines) + "\n)\n"


def _render_row(row: VocabularyRow) -> str:
    fields = [
        json.dumps(row.name),
        _render_tuple(row.labels),
        json.dumps(row.category.value),
        _render_optional(row.piping_kind),
        _render_optional(row.tag_prefix),
        "True" if row.leaf else "False",
    ]
    return f"    _row({', '.join(fields)}),"


def _render_tuple(items: tuple[str, ...]) -> str:
    """A tuple literal; a one-item tuple needs its trailing comma."""
    body = ", ".join(json.dumps(item) for item in items)
    return f"({body},)" if len(items) == 1 else f"({body})"


def _render_optional(value: str | None) -> str:
    return "None" if value is None else json.dumps(value)
